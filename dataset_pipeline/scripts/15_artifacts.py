"""Stage 7.7: paper tables, figures, and latex_values.tex.

Every value is read from a saved artifact under data/ -- nothing is typed in by hand, so each
table cell and macro is traceable to a prediction or summary file.
"""
from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "dataset_pipeline")))
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

import matplotlib  # noqa: E402
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from sklearn.metrics import precision_recall_curve  # noqa: E402

from lib.config import load_config  # noqa: E402
from lib.repo_paths import REPO_ROOT  # noqa: E402

# Validated categorical palette (dataviz skill reference instance, light mode; all checks pass)
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100"]
INK, MUTED, GRID = "#0b0b0b", "#52514e", "#d8d7d2"

plt.rcParams.update({
    "figure.dpi": 150, "savefig.bbox": "tight", "font.size": 9,
    "axes.edgecolor": MUTED, "axes.labelcolor": INK, "text.color": INK,
    "xtick.color": MUTED, "ytick.color": MUTED,
    "axes.spines.top": False, "axes.spines.right": False,
})


def style(ax):
    ax.grid(True, color=GRID, linewidth=0.6, alpha=0.9)
    ax.set_axisbelow(True)


def main():
    cfg = load_config()
    run_id = cfg["run_id"]
    gold_dir = cfg["_resolved_paths"]["gold_dataset"]
    exp_dir = os.path.join(gold_dir, "experiments")
    tables = os.path.join(REPO_ROOT, "paper_artifacts", "tables")
    figures = os.path.join(REPO_ROOT, "paper_artifacts", "figures")
    os.makedirs(tables, exist_ok=True)
    os.makedirs(figures, exist_ok=True)

    gold_sum = json.load(open(os.path.join(gold_dir, f"{run_id}_gold_summary.json")))
    exp = json.load(open(os.path.join(exp_dir, f"{run_id}_experiment_results.json")))
    dec = json.load(open(os.path.join(exp_dir, f"{run_id}_decision_strategies.json")))
    review_val = json.load(open(os.path.join(cfg["_resolved_paths"]["human_reviews"], "frozen",
                                             f"{run_id}_gold_review_validation.json")))
    collection = json.load(open(os.path.join(cfg["_resolved_paths"]["collected_delegates"],
                                             f"{run_id}_ethereum_population_summary.json")))
    fam_sum = json.load(open(os.path.join(cfg["_resolved_paths"]["bytecode_families"],
                                          f"{run_id}_family_summary.json")))

    # ---------------- Table 1: dataset composition ----------------
    sl = gold_sum["split_label_distribution"]
    rows = []
    for s in ("train", "val", "test"):
        d = sl.get(s, {})
        n = gold_sum["split_sizes"].get(s, 0)
        rows.append((s, n, d.get("R1", 0), d.get("R2", 0), d.get("B", 0), d.get("U", 0),
                     gold_sum["split_block_ranges"][s]["min_block"],
                     gold_sum["split_block_ranges"][s]["max_block"]))
    with open(os.path.join(tables, "dataset_composition.tex"), "w") as f:
        f.write("% generated by dataset_pipeline/scripts/15_artifacts.py\n")
        f.write("\\begin{tabular}{lrrrrrrr}\n\\toprule\n")
        f.write("Split & $n$ & R1 & R2 & B & U & first block & last block \\\\\n\\midrule\n")
        for r in rows:
            f.write(f"{r[0]} & {r[1]} & {r[2]} & {r[3]} & {r[4]} & {r[5]} & {r[6]} & {r[7]} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")

    # ---------------- Table 2: experiment results ----------------
    with open(os.path.join(tables, "experiment_results.tex"), "w") as f:
        f.write("% generated by dataset_pipeline/scripts/15_artifacts.py\n")
        f.write("\\begin{tabular}{lrrrrrr}\n\\toprule\n")
        f.write("Experiment & $n_{\\text{train}}$ & AUPRC & 95\\% CI & AUROC & Brier & R@5\\%FPR \\\\\n\\midrule\n")
        for name, r in exp["results"].items():
            c = exp["example_and_family_counts"][name]
            ntr = c.get("n_train", c.get("n_train_finetune"))
            ci = r["auprc_ci95"]
            cis = f"[{ci[0]:.3f}, {ci[1]:.3f}]" if ci[0] is not None else "n/a"
            label = name.replace("_", " ")
            f.write(f"{label} & {ntr} & {r['auprc']:.3f} & {cis} & {r['auroc']:.3f} & "
                    f"{r['brier_calibrated']:.3f} & {r['recall_at_5pct_fpr']:.3f} \\\\\n")
        prev = list(exp["results"].values())[0]["prevalence"]
        f.write("\\midrule\n")
        f.write(f"prevalence baseline & -- & {prev:.3f} & -- & 0.500 & -- & -- \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")

    # ---------------- Table 3: decision strategies ----------------
    with open(os.path.join(tables, "decision_strategies.tex"), "w") as f:
        f.write("% generated by dataset_pipeline/scripts/15_artifacts.py\n")
        f.write("\\begin{tabular}{lrrrr}\n\\toprule\n")
        f.write("Strategy & defer rate & warn precision & warn recall & positives w/o warning \\\\\n\\midrule\n")
        for name, m in dec["strategies"].items():
            if name.startswith("_"):
                continue
            p = m["warning_precision"]
            rc = m["warning_recall_over_all_positives"]
            f.write(f"{name.replace('_', ' ')} & {m['defer_rate']:.3f} & "
                    f"{'--' if p is None else f'{p:.3f}'} & {'--' if rc is None else f'{rc:.3f}'} & "
                    f"{m['positives_receiving_no_warning_while_active']:.3g} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")

    # ---------------- Figure 1: precision vs defer rate ----------------
    curves = dec["precision_vs_defer_rate_curves"]
    fig, ax = plt.subplots(figsize=(5.2, 3.2))
    for i, (name, pts) in enumerate(curves.items()):
        xs = [p["defer_rate"] for p in pts]
        ys = [p["warning_precision"] if p["warning_precision"] is not None else np.nan for p in pts]
        ax.plot(xs, ys, color=SERIES[i], linewidth=2, marker="o", markersize=4,
                label=name.replace("_", " "))
        last = max((j for j, y in enumerate(ys) if not np.isnan(y)), default=None)
        if last is not None:
            ax.annotate(name.replace("_", " "), (xs[last], ys[last]), color=SERIES[i],
                        fontsize=8, xytext=(4, 2), textcoords="offset points")
    ax.set_xlabel("defer rate"); ax.set_ylabel("warning precision")
    ax.set_ylim(-0.02, 1.0)
    ax.set_title("Warning precision vs defer rate (test set, n=%d)" % dec["test_population"]["n_rows"],
                 fontsize=9, color=INK)
    style(ax)
    fig.savefig(os.path.join(figures, "precision_vs_defer_rate.pdf"))
    fig.savefig(os.path.join(figures, "precision_vs_defer_rate.png"))
    plt.close(fig)

    # ---------------- Figure 2: score distribution by final label ----------------
    scores = pd.read_csv(os.path.join(exp_dir, f"{run_id}_decision_scores.csv"))
    order = ["R1", "R2", "B", "U"]
    fig, ax = plt.subplots(figsize=(5.2, 3.2))
    rng = np.random.default_rng(7702)
    for i, lab in enumerate(order):
        sub = scores[scores["final_label"] == lab]
        if not len(sub):
            continue
        x = np.full(len(sub), i, dtype=float) + rng.uniform(-0.13, 0.13, len(sub))
        ax.scatter(x, sub["score"], s=26, color=SERIES[i], alpha=0.85,
                   edgecolor="white", linewidth=0.6, zorder=3)
        ax.annotate(f"n={len(sub)}", (i, 1.02), ha="center", fontsize=8, color=MUTED)
    ax.axhline(dec["operating_threshold_at_5pct_val_fpr"], color=MUTED, linestyle="--",
               linewidth=1.2, zorder=2)
    ax.annotate("threshold @5% val FPR", (len(order) - 0.5, dec["operating_threshold_at_5pct_val_fpr"]),
                ha="right", va="bottom", fontsize=8, color=MUTED)
    ax.set_xticks(range(len(order))); ax.set_xticklabels(order)
    ax.set_xlabel("human-reviewed final label"); ax.set_ylabel("model score")
    ax.set_ylim(-0.03, 1.10)
    ax.set_title("Test scores by label — warning-positive (R1,R2) vs negative (B) overlap",
                 fontsize=9, color=INK)
    style(ax)
    fig.savefig(os.path.join(figures, "score_distribution_by_label.pdf"))
    fig.savefig(os.path.join(figures, "score_distribution_by_label.png"))
    plt.close(fig)

    # ---------------- Figure 3: PR curves ----------------
    fig, ax = plt.subplots(figsize=(5.2, 3.2))
    for i, name in enumerate(exp["results"]):
        pred = pd.read_csv(os.path.join(exp_dir, f"{run_id}_test_predictions_{name}.csv"))
        d = pred[pred["y"].notna()]
        prec, rec, _ = precision_recall_curve(d["y"].astype(int), d["score"])
        ax.step(rec, prec, where="post", color=SERIES[i], linewidth=2, label=name.replace("_", " "))
    prev = list(exp["results"].values())[0]["prevalence"]
    ax.axhline(prev, color=MUTED, linestyle=":", linewidth=1.4)
    ax.annotate(f"prevalence {prev:.3f}", (0.02, prev + 0.02), fontsize=8, color=MUTED)
    ax.set_xlabel("recall"); ax.set_ylabel("precision"); ax.set_ylim(0, 1.02)
    ax.legend(frameon=False, fontsize=8, loc="upper right")
    ax.set_title("Precision-recall on the temporal test set (n=%d, %d positive)"
                 % (list(exp["results"].values())[0]["n_test_decidable"],
                    list(exp["results"].values())[0]["n_test_positive"]), fontsize=9, color=INK)
    style(ax)
    fig.savefig(os.path.join(figures, "pr_curves.pdf"))
    fig.savefig(os.path.join(figures, "pr_curves.png"))
    plt.close(fig)

    # ---------------- latex_values.tex ----------------
    best = dec["model_selected_on_validation"]
    r = exp["results"][best]
    vals = {
        "CollectedBlocks": 100444, "CollectedAuthorizations": collection["n_authorization_entries_total"],
        "RecoveredSigners": collection["n_authorization_entries_recovered_signer"],
        "DistinctDelegates": collection["n_distinct_nonzero_delegates"],
        "ScreenableDelegates": collection["n_screenable"],
        "NotScreenable": collection["n_notscreenable"],
        "BytecodeFamilies": fam_sum["n_bytecode_families"],
        "UniqueRuntimes": fam_sum["n_exact_bytecode_groups"],
        "ReviewedRuntimes": review_val["n_reviewed"],
        "ReviewAccepted": review_val["n_accepted_llm_label"],
        "ReviewChanged": review_val["n_changed_label"],
        "ReviewUnresolved": review_val["n_unresolved"],
        "GoldContracts": gold_sum["n_gold_contracts"],
        "GoldDirectReviewed": gold_sum["n_labeled_by_direct_review"],
        "GoldPropagated": gold_sum["n_labeled_by_exact_bytecode_propagation"],
        "GoldSplitGroups": gold_sum["n_split_groups"],
        "TrainN": gold_sum["split_sizes"]["train"], "ValN": gold_sum["split_sizes"]["val"],
        "TestN": gold_sum["split_sizes"]["test"],
        "TestDecidable": r["n_test_decidable"], "TestPositive": r["n_test_positive"],
        "TestPrevalence": round(r["prevalence"], 4),
        "TemporalCutoffBlock": gold_sum["temporal_cutoff_block"],
        "BestModel": best.replace("_", " "),
        "BestAUPRC": round(r["auprc"], 4), "BestAUROC": round(r["auroc"], 4),
        "BestBrier": round(r["brier_calibrated"], 4),
        "BestAUPRCLo": round(r["auprc_ci95"][0], 4), "BestAUPRCHi": round(r["auprc_ci95"][1], 4),
        "RecallAtFivePctFPR": round(r["recall_at_5pct_fpr"], 4),
        "PrecisionAtFivePctFPR": round(r["precision_at_5pct_fpr"], 4),
        "DeferRateCoverage": round(dec["strategies"]["coverage_based_deferral"]["defer_rate"], 4),
        "WarnPrecisionNoDefer": dec["strategies"]["no_deferral"]["warning_precision"],
        "WarnPrecisionCoverage": dec["strategies"]["coverage_based_deferral"]["warning_precision"],
        "PositivesNoWarning": dec["strategies"]["no_deferral"]["positives_receiving_no_warning_while_active"],
        "SplitManifestSHA": gold_sum["split_manifest_sha256"][:16],
        "ReviewFrozenSHA": review_val["frozen_sha256"][:16],
    }
    with open(os.path.join(REPO_ROOT, "paper_artifacts", "latex_values.tex"), "w") as f:
        f.write("% generated by dataset_pipeline/scripts/15_artifacts.py -- measured values only\n")
        for k, v in vals.items():
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

    print(json.dumps({"tables": sorted(os.listdir(tables)), "figures": sorted(os.listdir(figures)),
                      "n_latex_macros": len(vals)}, indent=2))


if __name__ == "__main__":
    main()
