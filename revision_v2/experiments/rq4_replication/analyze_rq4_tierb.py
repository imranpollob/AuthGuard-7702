#!/usr/bin/env python3
"""RQ4 Tier-B three-seed analysis, plus the comparison against the full-action replication.

Reuses the metric and contrast definitions in rq4_metrics.py unchanged, so the Tier-B and
full-action numbers are produced by identical code paths and differ only in the action
space the attacker was allowed to search.

The full-action results are read read-only from revision_v2/results/rq4_replication_3seed/
and are never modified.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
RV2 = os.path.abspath(os.path.join(HERE, "..", ".."))
ATTACKS = os.path.join(RV2, "results", "adaptive_attacks_v2")
OUT = os.path.join(RV2, "results", "rq4_replication_3seed_tierb")
FULL = os.path.join(RV2, "results", "rq4_replication_3seed")
sys.path.insert(0, HERE)
import rq4_metrics as M  # noqa: E402

PARAM_COUNTS = {"chunk_attention_16384": 30_050,
                "chunk_mean_16384": 29_985,
                "flat_control_16384": 29_985}
LABEL = {"chunk_attention_16384": "Chunk attention",
         "chunk_mean_16384": "Chunk mean",
         "flat_control_16384": "Flat control"}
SEEDS = [7702, 7703, 7704]
EXCLUDED = ("address", "selector")


def commit():
    return subprocess.run(["git", "rev-parse", "HEAD"], cwd=RV2,
                          capture_output=True, text=True).stdout.strip()


def load():
    frames, used = {}, {}
    for seed in SEEDS:
        p = os.path.join(ATTACKS, f"attack_per_row_tierb_s{seed}.csv.gz")
        if not os.path.exists(p):
            continue
        f = pd.read_csv(p)
        seeds_in = sorted(f.seed.unique())
        if seeds_in != [seed]:
            raise SystemExit(f"{p} holds seeds {seeds_in}, expected [{seed}]")
        frames[seed] = f[f.target_model.isin(M.MODELS)]
        used[seed] = os.path.relpath(p, RV2)
    return frames, used


def thresholds_for(seed):
    p = os.path.join(ATTACKS, f"thresholds_tierb_s{seed}.csv")
    if not os.path.exists(p):
        return {}
    t = pd.read_csv(p)
    return {(int(r.fold), r.model): float(r.threshold_05)
            for _, r in t[t.model.isin(M.MODELS)].iterrows()}


def verify_sequences(frames):
    """Empirical proof, read off the produced records, that the search never used a
    Tier-C action. This is stronger than the pre-run audit: it inspects what the attack
    actually emitted. The fixed comparators M2/M3 (and therefore fixed_oracle_best) are
    generated by a separate code path that the action restriction does not govern; they
    are recorded in the raw file and excluded from every Tier-B statistic."""
    out = {}
    for seed, f in sorted(frames.items()):
        searched = f[f.method.isin(M.SEARCH_METHODS)]
        used = set()
        for s in searched.sequence.dropna().unique():
            used.update(str(s).split("+"))
        # "clean_noop" is the runner's placeholder for an empty sequence, not an action.
        n_noop = int((searched.sequence == "clean_noop").sum())
        used.discard("clean_noop")
        leaked = sorted(used & set(EXCLUDED))
        if leaked:
            raise SystemExit(f"seed {seed}: Tier-C action {leaked} present in a searched "
                             "sequence; the restriction did not hold")
        out[seed] = dict(
            searched_rows=int(len(searched)),
            distinct_actions_used=sorted(used),
            empty_sequence_rows=n_noop,
            tier_c_actions_observed=leaked,
            excluded_from_statistics=sorted(
                set(f.method.unique()) - set(M.SEARCH_METHODS)),
            excluded_row_count=int((~f.method.isin(M.SEARCH_METHODS)).sum()))
    return out


def per_seed_rows(frames):
    rows = []
    for seed, f in sorted(frames.items()):
        thr = thresholds_for(seed)
        for model in M.MODELS:
            g = f[f.target_model == model]
            if not len(g):
                continue
            clean, n_obs = M.clean_detection(f, model)
            rnd = M.marginal(f, model, "random_search")
            beam = M.marginal(f, model, "beam_search")
            rr = M.robust_recall(f, model)
            searches = g[g.method.isin(M.SEARCH_METHODS)]
            elig = searches[searches.clean_detected]
            rows.append(dict(
                seed=seed, architecture=LABEL[model], model_key=model,
                trainable_parameters=PARAM_COUNTS[model],
                clean_detection_rate=clean, n_positive_observations=n_obs,
                validation_thresholds_by_fold=sorted(
                    round(v, 6) for (fold, m), v in thr.items() if m == model),
                n_eligible_observations=rnd["n_eligible"],
                n_eligible_families=rnd["n_eligible_families"],
                random_successes=rnd["successes"], random_ASR=rnd["ASR"],
                beam_successes=beam["successes"], beam_ASR=beam["ASR"],
                robust_recall=rr["robust_recall"],
                invalid_attack_records=int((~searches.structural_valid).sum()),
                failed_attack_records=int((~elig.attack_success).sum()),
                total_attack_queries=int(searches.queries.sum())))
    return rows


def contrasts(frames, nboot):
    out = []
    for seed, f in sorted(frames.items()):
        for method in M.SEARCH_METHODS:
            for left in ["chunk_mean_16384", "flat_control_16384"]:
                c = M.paired_contrast(f, left, "chunk_attention_16384", method,
                                      f"tierb_seed{seed}", nboot)
                if c:
                    c.update(seed=seed, scope="per_seed", action_space="tier_b",
                             estimator="family-clustered bootstrap within seed")
                    out.append(c)
    return out


def seed_averaged(frames, left, right, method, nboot):
    per_source = {}
    for seed, f in sorted(frames.items()):
        a = f[(f.target_model == left) & (f.method == method)].set_index(M.KEY).sort_index()
        b = f[(f.target_model == right) & (f.method == method)].set_index(M.KEY).sort_index()
        shared = a.index.intersection(b.index)
        if not len(shared):
            continue
        a, b = a.loc[shared], b.loc[shared]
        elig = a.clean_detected.to_numpy(bool) & b.clean_detected.to_numpy(bool)
        sa, sb = a.attack_success.to_numpy(float), b.attack_success.to_numpy(float)
        fam = a.family_id.to_numpy()
        for i, key in enumerate(a.index):
            if elig[i]:
                per_source.setdefault(key[2], dict(family=fam[i], d=[]))["d"].append(
                    sa[i] - sb[i])
    if not per_source:
        return None
    sids = sorted(per_source)
    delta = np.asarray([np.mean(per_source[s]["d"]) for s in sids])
    fams = np.asarray([per_source[s]["family"] for s in sids])
    draws, n_fam = M._family_bootstrap(
        fams, delta, np.ones(len(delta), bool),
        f"tierb:seedavg:{left}:{right}:{method}", nboot)
    ci = [float(np.percentile(draws, 2.5)), float(np.percentile(draws, 97.5))]
    return dict(label="three_seed_family_clustered_seed_averaged", action_space="tier_b",
                contrast=f"{left} - {right}", method=method, scope="three_seed",
                estimator=("per-source difference averaged over seeds where both models "
                           "detect cleanly, then family-clustered bootstrap"),
                difference=float(delta.mean()), ci_low=ci[0], ci_high=ci[1],
                excludes_zero=bool(ci[0] > 0 or ci[1] < 0),
                n_sources=int(len(delta)), n_families_eligible=int(n_fam),
                bootstrap_replicates=int(len(draws)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nboot", type=int, default=M.NBOOT)
    args = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    frames, used = load()
    if len(frames) != 3:
        raise SystemExit(f"expected 3 seeds, found {sorted(frames)}")
    print(f"[tierb] seeds: {sorted(frames)}", flush=True)

    seq_check = verify_sequences(frames)
    with open(os.path.join(OUT, "tierb_sequence_verification.json"), "w") as fh:
        json.dump(seq_check, fh, indent=2)
    for seed, v in seq_check.items():
        print(f"[tierb] seed {seed}: actions actually searched = "
              f"{v['distinct_actions_used']}  (Tier-C observed: "
              f"{v['tier_c_actions_observed'] or 'none'})")

    rows = per_seed_rows(frames)
    per_seed = pd.DataFrame(rows)
    per_seed.to_csv(os.path.join(OUT, "rq4_tierb_per_seed.csv"), index=False)

    cons = contrasts(frames, args.nboot)
    for method in M.SEARCH_METHODS:
        for left in ["chunk_mean_16384", "flat_control_16384"]:
            c = seed_averaged(frames, left, "chunk_attention_16384", method, args.nboot)
            if c:
                cons.append(c)
    cf = pd.DataFrame([c for c in cons if c.get("scope") == "per_seed"])
    for (contrast, method), grp in cf.groupby(["contrast", "method"]):
        cons.append(dict(
            label="three_seed_mean_of_seed_level_estimates", action_space="tier_b",
            contrast=contrast, method=method, scope="three_seed",
            estimator="mean and SD across per-seed family-clustered point estimates",
            difference=float(grp.difference.mean()),
            sd_across_seeds=float(grp.difference.std(ddof=0)),
            n_seeds=int(grp.seed.nunique()),
            min_seed_effect=float(grp.difference.min()),
            max_seed_effect=float(grp.difference.max()),
            all_seeds_positive=bool((grp.difference > 0).all()),
            all_seed_cis_exclude_zero=bool(grp.excludes_zero.all())))
    pd.DataFrame(cons).to_csv(os.path.join(OUT, "rq4_tierb_contrasts.csv"), index=False)

    agg = []
    for model in M.MODELS:
        g = per_seed[per_seed.model_key == model]
        agg.append(dict(
            architecture=LABEL[model], model_key=model,
            trainable_parameters=PARAM_COUNTS[model], n_seeds=int(g.seed.nunique()),
            clean_detection_mean=float(g.clean_detection_rate.mean()),
            clean_detection_sd=float(g.clean_detection_rate.std(ddof=0)),
            random_ASR_mean=float(g.random_ASR.mean()),
            random_ASR_sd=float(g.random_ASR.std(ddof=0)),
            beam_ASR_mean=float(g.beam_ASR.mean()),
            beam_ASR_sd=float(g.beam_ASR.std(ddof=0)),
            robust_recall_mean=float(g.robust_recall.mean()),
            robust_recall_sd=float(g.robust_recall.std(ddof=0))))
    pd.DataFrame(agg).to_csv(os.path.join(OUT, "rq4_tierb_aggregate.csv"), index=False)

    # ---- Step 4: comparison against the full-action replication (read-only) ----
    comparison = []
    full_per_seed = pd.read_csv(os.path.join(FULL, "rq4_replication_per_seed.csv"))
    full_con = pd.read_csv(os.path.join(FULL, "rq4_replication_contrasts.csv"))
    for model in M.MODELS:
        tb = per_seed[per_seed.model_key == model]
        fa = full_per_seed[full_per_seed.model_key == model]
        for metric in ["random_ASR", "beam_ASR", "clean_detection_rate", "robust_recall"]:
            comparison.append(dict(
                architecture=LABEL[model], metric=metric,
                tier_b_mean=float(tb[metric].mean()), tier_b_sd=float(tb[metric].std(ddof=0)),
                full_action_mean=float(fa[metric].mean()),
                full_action_sd=float(fa[metric].std(ddof=0)),
                delta_tierb_minus_full=float(tb[metric].mean() - fa[metric].mean())))
    pd.DataFrame(comparison).to_csv(
        os.path.join(OUT, "rq4_tierb_vs_full_action.csv"), index=False)

    tb_sa = pd.DataFrame([c for c in cons
                          if c.get("label") == "three_seed_family_clustered_seed_averaged"])
    fa_sa = full_con[full_con.label == "three_seed_family_clustered_seed_averaged"]
    contrast_cmp = []
    for _, r in tb_sa.iterrows():
        m = fa_sa[(fa_sa.contrast == r.contrast) & (fa_sa.method == r.method)]
        if len(m):
            f = m.iloc[0]
            contrast_cmp.append(dict(
                contrast=r.contrast, method=r.method,
                tier_b_effect=float(r.difference),
                tier_b_ci=[float(r.ci_low), float(r.ci_high)],
                full_action_effect=float(f.difference),
                full_action_ci=[float(f.ci_low), float(f.ci_high)],
                delta=float(r.difference - f.difference),
                both_exclude_zero=bool(r.excludes_zero and f.excludes_zero)))

    summary = dict(
        experiment="RQ4 parameter-matched aggregation controls, Tier-B action space only",
        git_commit=commit(), seeds=sorted(frames), folds=[0, 1, 2, 3, 4],
        models=M.MODELS, parameter_counts=PARAM_COUNTS,
        action_space=["metadata", "neutral25", "flood25", "flood50", "flood100", "flood200"],
        excluded_actions=["address", "selector"],
        query_budget=64, beam_width=4, max_depth=4, max_byte_overhead=2.0,
        operating_point="nominal 5% FPR from validation negatives",
        bootstrap_replicates=args.nboot, source_files=used,
        sequence_verification=seq_check,
        per_seed=rows, aggregate=agg, contrasts=cons,
        comparison_marginals=comparison, comparison_contrasts=contrast_cmp,
        full_action_reference_dir=os.path.relpath(FULL, RV2),
        output_dir=os.path.relpath(OUT, RV2))
    with open(os.path.join(OUT, "rq4_tierb_summary.json"), "w") as fh:
        json.dump(summary, fh, indent=2, default=str)

    for seed, rel in used.items():
        src = os.path.join(RV2, rel)
        dst = os.path.join(OUT, "raw_" + os.path.basename(src))
        if not os.path.exists(dst):
            pd.read_csv(src).to_csv(dst, index=False, compression="gzip")

    print(per_seed[["seed", "architecture", "clean_detection_rate", "random_ASR",
                    "beam_ASR", "robust_recall", "n_eligible_observations",
                    "n_eligible_families"]].round(4).to_string(index=False))
    print("\n[tierb] seed-averaged contrasts:")
    for _, r in tb_sa.iterrows():
        print(f"   {r.contrast:<46}{r.method:<15}{r.difference:+.4f} "
              f"[{r.ci_low:+.4f},{r.ci_high:+.4f}] excl0={r.excludes_zero}")
    print(f"\n[tierb] wrote {OUT}")


if __name__ == "__main__":
    main()
